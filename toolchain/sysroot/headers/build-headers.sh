# build-headers.sh [--update-pins] OUTDIR
#
# Builds the C library, kernel and CoreFoundation headers of the sysroot from Apple's published
# open-source releases, and writes them to OUTDIR, which must not exist yet or must be an empty
# directory:
#   OUTDIR/usr/include/...                                              C library, POSIX, Mach, BSD
#   OUTDIR/System/Library/Frameworks/CoreFoundation.framework/Headers/... CoreFoundation
# The other frameworks' headers (Foundation, UIKit, ...) are not made here (a later stage).
# No file of Apple's iPhone SDK is read, and the script works without one. ../README.md says what
# was compared and how.
#
# The input is sources.tsv, the file next to this script: one row per installed header, naming the
# published file it is made from (repository, tag, commit, path, sha256) and the processing, or a
# file of this project under own/. Rows of kind "in" name further published files that the
# processing reads (the .defs files that mig preprocesses, the sources of mig itself). The header
# of sources.tsv describes the fields.
#
# The processing rules. Each one is what the release's own install step does, with the settings of
# an iPhone OS build:
#   none      the published file as it is
#   libc      Libc's "installhdrs" (Libc-498.1.7 Makefile.xbs, target modifyhdrs): every block from a
#             line "//Begin-Libc" to the next line "//End-Libc" is deleted (strip-header.ed), and a
#             file that mentions UNIFDEF goes through
#               unifdef -UUNIFDEF_LEGACY_64_APIS -UUNIFDEF_LEGACY_RUNE_APIS -UUNIFDEF_LEGACY_UTMP_APIS
#                       -DUNIFDEF_MOVE_LOCALTIME
#             (the feature set of Platforms/iPhone/Makefile.inc: no legacy 64, rune or utmp APIs,
#             localtime moved)
#   xnu       xnu's rule for exported user headers (makedefs/MakeInc.rule, INSTALL_MI/MD): unifdef with
#             SINCFRAME_UNIFDEF of makedefs/MakeInc.def, identical in xnu-1228.15.4 and xnu-1456.1.26:
#               -UMACH_KERNEL_PRIVATE -UBSD_KERNEL_PRIVATE -UIOKIT_KERNEL_PRIVATE -ULIBKERN_KERNEL_PRIVATE
#               -ULIBSA_KERNEL_PRIVATE -UPEXPERT_KERNEL_PRIVATE -UXNU_KERNEL_PRIVATE
#               -UKERNEL_PRIVATE -UKERNEL -UPRIVATE -D_OPEN_SOURCE_
#   xnu-bsd-sys  the xnu rule with bsd/sys/Makefile's addition for the product being built
#             (EXTRAUNIFDEF, PRODUCT=iPhone): -UPRODUCT_AppleTV -DPRODUCT_iPhone -UPRODUCT_MacOSX.
#             Used for the headers of bsd/sys; of them only sys/cdefs.h tests a PRODUCT_ symbol.
#   xnu-4570  the same rule as xnu-4570.1.46 has it, for PLATFORM=iPhoneOS: the flags above, plus
#             -D__OPEN_SOURCE__, -DPLATFORM_iPhoneOS and -UPLATFORM_<x> for its other platforms
#   carbon    CarbonHeaders-18.1's Makefile (target install) for the iPhone build: the placeholders
#             @CONFIG_EMBEDDED@, @CONFIG_IPHONE@, @CONFIG_IPHONE_SIMULATOR@ become 1, 1, 0
#   mig       the header is generated by Apple's interface generator mig from the named .defs file,
#             as xnu's libsyscall does it (libsyscall/Makefile.xbs: mig -arch <arch> -header X.h X.defs):
#             the .defs is preprocessed for ARMv6 with -D__MACH30__, the directory of the .defs, the
#             published .defs files of the "in" rows and the headers built here as include path, and
#             migcom writes the user header. migcom is built first from bootstrap_cmds-72 (see below).
# A processing field "RULE+patch:NAME" applies patches/NAME after the rule. A patch can change several
# files (one topic); it is applied once, with "git apply" (exact context, no fuzz), and every file it
# changes must name it. Each patch begins with a comment that says what it changes and why.
#
# mig. bootstrap_cmds-72 is the mig of the time (Mac OS X 10.6). Its migcom is built here with the
# host C compiler, bison (as yacc) and flex, from the published sources in the "in" rows, with two
# files of this project: patches/migcom-64bit-host.patch (migcom assumes a 32-bit host; see the patch)
# and own/migcom-host/mach/*.h, the few Mach message types and constants that migcom's own sources
# include (the host is not a Mach system). migcom computes message sizes from them; they describe the
# 32-bit layout of the target.
#
# Checks. Every published file is checked against the sha256 of its row before it is used, and every
# file of own/ too. After the build the tree must hold exactly the "hdr" rows, and every file must
# match HEADERS.sha256 (next to this script). On any mismatch the script stops and writes nothing to
# OUTDIR. --update-pins rewrites HEADERS.sha256 from the result instead of checking it (for a
# deliberate change of sources.tsv; review the diff).
#
# Fetching. For each release, the commit of its rows is fetched from
# https://github.com/apple-oss-distributions/<repo> (shallow, partial, only the files needed), unless
# IOS3_OSS_CACHE names a directory that holds <repo>/<tag>/ already (a checkout of that release; if it
# is a git work tree, its HEAD must be the pinned commit). The sha256 pins are checked all the same.
#
# Needs: bash, git, sha256sum, awk, sed, unifdef (2.x), the host clang (as the preprocessor for mig;
#   IOS3_HOST_CLANG, default clang-18 if present, else clang), a host C compiler for migcom (HOST_CC,
#   default cc), bison (BISON, default bison) and flex (FLEX, default flex). No SDK.
#
# Environment:
#   IOS3_OSS_CACHE   directory with <repo>/<tag>/ checkouts of the releases (replaces the fetch)
#   IOS3_HOST_CLANG  the host clang, as in armv6-ios3-clang
#   HOST_CC, BISON, FLEX   tools for building migcom
set -euo pipefail

die() { echo "build-headers: ERROR: $*" >&2; exit 1; }

UPDATE_PINS=0
if [ "${1:-}" = --update-pins ]; then UPDATE_PINS=1; shift; fi
[ $# = 1 ] && [ -n "$1" ] || { echo "usage: build-headers.sh [--update-pins] OUTDIR" >&2; exit 2; }
OUT="$1"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
SOURCES="$HERE/sources.tsv"
PINS="$HERE/HEADERS.sha256"
[ -f "$SOURCES" ] || die "$SOURCES not found (the list of headers and their sources; it belongs next to this script)"
[ $UPDATE_PINS = 1 ] || [ -f "$PINS" ] || die "$PINS not found (the sha256 of every built header; it belongs next to this script)"
if [ -e "$OUT" ] || [ -L "$OUT" ]; then
  [ -d "$OUT" ] && [ ! -L "$OUT" ] && [ -z "$(ls -A "$OUT")" ] \
    || die "$OUT exists and is not an empty directory: the headers go into a new tree (this script never overwrites or adds to one)"
fi

HOSTCLANG="${IOS3_HOST_CLANG:-}"
if [ -z "$HOSTCLANG" ]; then
  if command -v clang-18 >/dev/null; then HOSTCLANG=clang-18; else HOSTCLANG=clang; fi
fi
HOST_CC="${HOST_CC:-cc}"; BISON="${BISON:-bison}"; FLEX="${FLEX:-flex}"
for t in git sha256sum awk sed sort unifdef "$HOSTCLANG" "$HOST_CC" "$BISON" "$FLEX"; do
  command -v "$t" >/dev/null || die "$t not found"
done
export LC_ALL=C

W="$(mktemp -d "${TMPDIR:-/tmp}/headers.XXXXXX")"
trap 'rm -rf "$W"' EXIT
mkdir "$W/rel" "$W/root" "$W/in" "$W/mig"

# ---- 1. sources.tsv ---------------------------------------------------------------------------------
# Rows: kind path repo tag commit file sha256 processing (tab-separated; '#' starts a comment line).
grep -v '^#' "$SOURCES" > "$W/rows.tsv"
sort -c "$W/rows.tsv" 2>/dev/null || die "$SOURCES: the rows are not sorted (LC_ALL=C sort)"
awk -F'\t' '
  NF != 8 { print "line " NR ": " NF " fields, not 8"; bad = 1; next }
  $1 != "hdr" && $1 != "in" { print "line " NR ": kind " $1; bad = 1 }
  $2 !~ /^[A-Za-z0-9_.+\/-]+$/ || $2 ~ /(^|\/)\.\.?(\/|$)/ { print "line " NR ": path " $2; bad = 1 }
  $6 ~ /(^|\/)\.\.(\/|$)/ || $6 ~ /^\// { print "line " NR ": file " $6; bad = 1 }
  $7 !~ /^[0-9a-f]{64}$/ { print "line " NR ": sha256 " $7; bad = 1 }
  $3 == "own" && ($4 != "-" || $5 != "-" || $6 !~ /^own\//) { print "line " NR ": own row"; bad = 1 }
  $3 != "own" && $5 !~ /^[0-9a-f]{40}$/ { print "line " NR ": commit " $5; bad = 1 }
  seen[$1 "\t" $2]++ { print "line " NR ": duplicate " $2; bad = 1 }
  END { exit bad }' "$W/rows.tsv" >&2 || die "$SOURCES is not well-formed"
# one commit per release
awk -F'\t' '$3 != "own" { k = $3 "\t" $4; if (k in c && c[k] != $5) { print k; bad = 1 } c[k] = $5 } END { exit bad }' "$W/rows.tsv" >&2 \
  || die "$SOURCES names two commits for one release"

# ---- 2. the published files, at the pinned commits ----------------------------------------------------
while IFS=$'\t' read -r repo tag commit; do
  awk -F'\t' -v r="$repo" -v t="$tag" '$3 == r && $4 == t { print $6 }' "$W/rows.tsv" | sort -u > "$W/files.lst"
  if [ -n "${IOS3_OSS_CACHE:-}" ] && [ -d "$IOS3_OSS_CACHE/$repo/$tag" ]; then
    src="$IOS3_OSS_CACHE/$repo/$tag"
    if [ -e "$src/.git" ]; then
      [ "$(git -C "$src" rev-parse HEAD)" = "$commit" ] || die "$src is not at commit $commit ($repo $tag)"
    fi
    echo "build-headers: $repo $tag: from $src (IOS3_OSS_CACHE)"
  else
    src="$W/rel/$repo@$tag"
    echo "build-headers: $repo $tag: fetching https://github.com/apple-oss-distributions/$repo @ $commit"
    git init -q "$src"
    git -C "$src" remote add origin "https://github.com/apple-oss-distributions/$repo"
    git -C "$src" config core.sparseCheckout true
    sed 's|^|/|' "$W/files.lst" > "$src/.git/info/sparse-checkout"
    git -C "$src" -c core.autocrlf=false fetch -q --depth 1 --filter=blob:none origin "$commit" \
      || die "could not fetch $commit from https://github.com/apple-oss-distributions/$repo"
    git -C "$src" -c core.autocrlf=false -c advice.detachedHead=false checkout -q --detach FETCH_HEAD
    [ "$(git -C "$src" rev-parse HEAD)" = "$commit" ] || die "the fetch did not give commit $commit ($repo $tag)"
  fi
  while IFS= read -r f; do
    [ -f "$src/$f" ] && [ ! -L "$src/$f" ] || die "$repo $tag: $f is not a regular file in that release"
    mkdir -p "$(dirname "$W/in/$repo/$tag/$f")"
    cp "$src/$f" "$W/in/$repo/$tag/$f"
  done < "$W/files.lst"
done < <(awk -F'\t' '$3 != "own" { print $3 "\t" $4 "\t" $5 }' "$W/rows.tsv" | sort -u)
# own files are read from this directory
while IFS=$'\t' read -r f; do
  [ -f "$HERE/$f" ] || die "$HERE/$f not found"
  mkdir -p "$(dirname "$W/in/own/$f")"; cp "$HERE/$f" "$W/in/own/$f"
done < <(awk -F'\t' '$3 == "own" { print $6 }' "$W/rows.tsv" | sort -u)
awk -F'\t' '{ if ($3 == "own") p = "own/" $6; else p = $3 "/" $4 "/" $6; print $7 "  " p }' "$W/rows.tsv" | sort -u > "$W/in.sha256"
( cd "$W/in" && sha256sum -c --strict --quiet "$W/in.sha256" ) || die "an input file does not match the sha256 of its row in sources.tsv"
echo "build-headers: $(wc -l < "$W/in.sha256") input files match their sha256"

src_of() { if [ "$1" = own ]; then echo "$W/in/own/$3"; else echo "$W/in/$1/$2/$3"; fi; }   # repo tag file

# ---- 3. the processing rules ---------------------------------------------------------------------------
XNU_SINC=(-UMACH_KERNEL_PRIVATE -UBSD_KERNEL_PRIVATE -UIOKIT_KERNEL_PRIVATE -ULIBKERN_KERNEL_PRIVATE
          -ULIBSA_KERNEL_PRIVATE -UPEXPERT_KERNEL_PRIVATE -UXNU_KERNEL_PRIVATE
          -UKERNEL_PRIVATE -UKERNEL -UPRIVATE -D_OPEN_SOURCE_)
XNU4570_PLATFORM=(-UPLATFORM_MacOSX -UPLATFORM_iPhoneSimulator -UPLATFORM_iPhoneNanoSimulator -UPLATFORM_tvSimulator
                  -UPLATFORM_AppleTVSimulator -UPLATFORM_WatchSimulator -DPLATFORM_iPhoneOS -UPLATFORM_iPhoneOSNano
                  -UPLATFORM_tvOS -UPLATFORM_AppleTVOS -UPLATFORM_WatchOS -UPLATFORM_BridgeOS)
LIBC_UNIFDEF=(-UUNIFDEF_LEGACY_64_APIS -UUNIFDEF_LEGACY_RUNE_APIS -UUNIFDEF_LEGACY_UTMP_APIS -DUNIFDEF_MOVE_LOCALTIME)
run_unifdef() {  # IN OUT ARGS...
  local in="$1" out="$2" rc=0; shift 2
  unifdef "$@" "$in" > "$out" || rc=$?
  [ $rc -le 1 ] || die "unifdef failed on $in"
}
apply_rule() {  # RULE IN OUT
  case "$1" in
    none) cp "$2" "$3" ;;
    xnu) run_unifdef "$2" "$3" "${XNU_SINC[@]}" ;;
    xnu-bsd-sys) run_unifdef "$2" "$3" "${XNU_SINC[@]}" -UPRODUCT_AppleTV -DPRODUCT_iPhone -UPRODUCT_MacOSX ;;
    xnu-4570) run_unifdef "$2" "$3" "${XNU4570_PLATFORM[@]}" "${XNU_SINC[@]}" -D__OPEN_SOURCE__ ;;
    libc)
      awk 'skip == 0 && $0 == "//Begin-Libc" { skip = 1; next }
           skip == 1 && $0 == "//End-Libc" { skip = 0; next }
           skip == 0 { print }
           END { if (skip) exit 3 }' "$2" > "$3.strip" || die "$2: //Begin-Libc without //End-Libc"
      if grep -q UNIFDEF "$3.strip"; then run_unifdef "$3.strip" "$3" "${LIBC_UNIFDEF[@]}"; else cp "$3.strip" "$3"; fi
      rm -f "$3.strip" ;;
    carbon) sed -e 's/@CONFIG_EMBEDDED@/1/g' -e 's/@CONFIG_IPHONE_SIMULATOR@/0/g' -e 's/@CONFIG_IPHONE@/1/g' "$2" > "$3" ;;
    *) die "unknown processing rule '$1'" ;;
  esac
}

# hdr rows that are not generated by mig, then "in" rows (they go to the work directory, not the tree)
while IFS=$'\t' read -r kind path repo tag commit file sum proc; do
  rule="${proc%%+*}"
  [ "$rule" = mig ] && continue
  if [ "$kind" = hdr ]; then dst="$W/root/$path"; else dst="$W/work/$path"; fi
  mkdir -p "$(dirname "$dst")"
  apply_rule "$rule" "$(src_of "$repo" "$tag" "$file")" "$dst"
done < "$W/rows.tsv"

# ---- 4. our patches ------------------------------------------------------------------------------------
# A patch names its files relative to the sysroot (a/usr/include/...) or, for "in" rows, relative to
# the work directory (a/migcom/...). Which files each patch changes is read from the patch and must be
# the rows that name it.
awk -F'\t' '{ n = split($8, p, "+"); for (i = 2; i <= n; i++) { sub(/^patch:/, "", p[i]); print p[i] "\t" $1 "\t" $2 } }' "$W/rows.tsv" | sort > "$W/patch-rows.tsv"
for pname in $(cut -f1 "$W/patch-rows.tsv" | sort -u); do
  pf="$HERE/patches/$pname"
  [ -f "$pf" ] || die "patch $pf not found"
  grep '^+++ b/' "$pf" | sed 's|^+++ b/||; s|\t.*||' | sort > "$W/p-files"
  awk -F'\t' -v p="$pname" '$1 == p { print $3 }' "$W/patch-rows.tsv" | sort > "$W/p-rows"
  cmp -s "$W/p-files" "$W/p-rows" || die "patches/$pname changes $(tr '\n' ' ' < "$W/p-files")but sources.tsv names it for $(tr '\n' ' ' < "$W/p-rows")"
  kinds="$(awk -F'\t' -v p="$pname" '$1 == p { print $2 }' "$W/patch-rows.tsv" | sort -u)"
  case "$kinds" in hdr) d="$W/root" ;; in) d="$W/work" ;; *) die "patches/$pname mixes header and input files" ;; esac
  ( cd "$d" && git apply -p1 --whitespace=nowarn "$pf" ) || die "patches/$pname does not apply"
  echo "build-headers: applied patches/$pname"
done

# ---- 5. mig ----------------------------------------------------------------------------------------------
if awk -F'\t' '$1 == "hdr" && $8 ~ /^mig/ { f = 1 } END { exit !f }' "$W/rows.tsv"; then
  M="$W/work/migcom"
  [ -f "$M/parser.y" ] && [ -f "$M/lexxer.l" ] || die "sources.tsv has no migcom sources (in rows migcom/...)"
  printf 'char *MigGenerationDate = "<no date>";\nchar *MigMoreData = "<no data>";\n' > "$M/ident.c"
  ( cd "$M" && "$BISON" -y -d -o parser.c parser.y && "$FLEX" -olexxer.c lexxer.l ) > "$W/migcom-gen.log" 2>&1 \
    || { cat "$W/migcom-gen.log" >&2; die "bison/flex failed on migcom's grammar"; }
  ( cd "$M" && "$HOST_CC" -O1 -w -std=gnu89 -D__private_extern__= -include sys/types.h -I. -I"$W/work/migcom-host" \
      -o migcom error.c global.c header.c mig.c routine.c server.c statement.c string.c type.c user.c utils.c \
      parser.c lexxer.c ident.c ) > "$W/migcom-cc.log" 2>&1 || { cat "$W/migcom-cc.log" >&2; die "migcom does not build"; }
  echo "build-headers: built migcom (bootstrap_cmds-72)"
  while IFS=$'\t' read -r kind path repo tag commit file sum proc; do
    [ "$kind" = hdr ] && [ "${proc%%+*}" = mig ] || continue
    base="$(basename "$file" .defs)"; d="$W/mig/$base"
    mkdir -p "$d/src"; cp "$(src_of "$repo" "$tag" "$file")" "$d/src/$base.defs"
    "$HOSTCLANG" -E -x c -target armv6-apple-ios3.0 -nostdinc -D__MACH30__ \
      -I"$d/src" -I"$W/work/mig-include" -I"$W/root/usr/include" "$d/src/$base.defs" > "$d/$base.i" 2> "$d/cpp.log" \
      || { cat "$d/cpp.log" >&2; die "preprocessing $file failed"; }
    ( cd "$d" && "$M/migcom" -user /dev/null -server /dev/null -header "$base.h" -sheader /dev/null < "$base.i" ) > "$d/mig.log" 2>&1 \
      || { cat "$d/mig.log" >&2; die "mig failed on $file"; }
    [ ! -s "$d/mig.log" ] || { cat "$d/mig.log" >&2; die "mig printed a message for $file"; }
    mkdir -p "$(dirname "$W/root/$path")"; cp "$d/$base.h" "$W/root/$path"
  done < "$W/rows.tsv"
  echo "build-headers: generated $(awk -F'\t' '$1 == "hdr" && $8 ~ /^mig/' "$W/rows.tsv" | wc -l) headers with mig"
fi

# ---- 6. the result against the rows and the pins; only then OUTDIR is touched ---------------------------
( cd "$W/root" && find . \( -type f -o -type l \) | sed 's|^\./||' | sort ) > "$W/built.lst"
awk -F'\t' '$1 == "hdr" { print $2 }' "$W/rows.tsv" | sort > "$W/want.lst"
cmp -s "$W/built.lst" "$W/want.lst" || { diff "$W/want.lst" "$W/built.lst" >&2; die "the built tree is not the list of hdr rows"; }
[ -z "$(find "$W/root" -type l)" ] || die "the built tree holds a symlink"
( cd "$W/root" && xargs -d '\n' sha256sum < "$W/built.lst" ) > "$W/HEADERS.sha256"
if [ $UPDATE_PINS = 1 ]; then
  cp "$W/HEADERS.sha256" "$PINS"
  echo "build-headers: --update-pins: wrote $PINS ($(wc -l < "$PINS") files)"
else
  if ! cmp -s "$W/HEADERS.sha256" "$PINS"; then
    diff "$PINS" "$W/HEADERS.sha256" >&2 || true
    die "the built headers do not match HEADERS.sha256 (unifdef: $(unifdef -V 2>&1 | head -n 1)); nothing written to $OUT"
  fi
fi
mkdir -p "$OUT"
( cd "$W/root" && find . -type d -exec chmod 755 {} + && find . -type f -exec chmod 644 {} + )
cp -R "$W/root/." "$OUT/"
echo "build-headers: $(wc -l < "$W/built.lst") headers written to $OUT; they match HEADERS.sha256"
